const escapeRegex = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export async function listInvoices(query) {
  const { page, limit, sort, from, to, type, q } = query;

  const filter = {};
  if (type) filter.type = type;
  if (from || to) {
    filter.issuedAt = {};
    if (from) filter.issuedAt.$gte = businessDayRange(from, DEFAULT_TIMEZONE).start;
    if (to) filter.issuedAt.$lt = businessDayRange(to, DEFAULT_TIMEZONE).end;
  }
  if (q) {
    const regex = new RegExp(escapeRegex(q), 'i');
    filter.$or = [{ invoiceNumber: regex }, { playerName: regex }];
  }

  const sortObject = resolveSort(sort, ['issuedAt', 'totalMinor', 'invoiceNumber'], '-issuedAt');
  const [invoices, total] = await Promise.all([
    Invoice.find(filter)
      .sort(sortObject)
      .skip((page - 1) * limit)
      .limit(limit)
      .lean(),
    Invoice.countDocuments(filter),
  ]);

  return {
    invoices: invoices.map(presentInvoice),
    pagination: paginationMeta(total, page, limit),
  };
}

export async function getInvoice(invoiceId) {
  const invoice = await Invoice.findById(invoiceId).lean();
  if (!invoice) throw errors.notFound('الفاتورة');
  return { invoice: presentInvoice(invoice) };
}

export async function getInvoiceByVisit(visitId) {
  const invoice = await Invoice.findOne({ visit: visitId }).lean();
  if (!invoice) throw errors.notFound('الفاتورة');
  return { invoice: presentInvoice(invoice) };
}

/**
 * BR-74 → BR-77: owner-approved hard delete. Restores stock, removes the stock
 * movements generated by this visit, then deletes the invoice, visit and its
 * sessions. No audit entry is written (owner decision).
 */
export async function deleteInvoice(invoiceId, { confirmInvoiceNumber }) {
  const result = await withTransaction(async (dbSession) => {
    const invoice = await Invoice.findById(invoiceId).session(dbSession);
    if (!invoice) throw errors.notFound('الفاتورة');

    if (invoice.invoiceNumber !== confirmInvoiceNumber) {
      throw errors.business(
        ERROR_CODES.INVOICE_CONFIRMATION_MISMATCH,
        'رقم الفاتورة غير مطابق. اكتب رقم الفاتورة بالكامل للتأكيد.',
        { expected: invoice.invoiceNumber },
      );
    }

    const visit = await Visit.findById(invoice.visit).session(dbSession);

    if (visit) {
      const quantities = new Map();
      for (const item of visit.items ?? []) {
        const key = String(item.product);
        quantities.set(key, (quantities.get(key) ?? 0) + item.qty);
      }

      for (const [productId, qty] of quantities) {
        await Product.updateOne(
          { _id: productId },
          { $inc: { stockQty: qty } },
          { session: dbSession },
        );
      }

      await StockMovement.deleteMany(
        { 'reference.id': visit._id, type: STOCK_MOVEMENT_TYPE.SALE },
        { session: dbSession },
      );
      await Session.deleteMany({ visit: visit._id }, { session: dbSession });
      await visit.deleteOne({ session: dbSession });
    }

    await invoice.deleteOne({ session: dbSession });

    return {
      invoiceId: String(invoice._id),
      invoiceNumber: invoice.invoiceNumber,
      visitId: visit ? String(visit._id) : null,
    };
  });

  emitEvent(SOCKET_EVENTS.INVOICE_DELETED, { invoiceId: result.invoiceId });
  return result;
}

